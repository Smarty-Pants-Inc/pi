import type * as nodeFs from "node:fs";
import { readFileSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { describe, expect, it, vi } from "vitest";
import { type BashOperations, type BashToolOutput, createBashToolDefinition } from "../src/core/tools/bash.ts";
import { FULL_OUTPUT_HEAD_BYTES, FULL_OUTPUT_TAIL_BYTES } from "../src/core/tools/output-accumulator.ts";
import { wrapToolDefinition } from "../src/core/tools/tool-definition-wrapper.ts";
import { formatSize, truncateTail } from "../src/core/tools/truncate.ts";
import { getOutputDirectoryBytes } from "../src/utils/output-files.ts";

// smarty-dev#11307: the bash tool's full-output log is capped and the tool result says so.
// No test here removes files: the process-owned output directory is removed at process exit.

const probe = vi.hoisted(() => ({ paths: [] as string[] }));

vi.mock("node:fs", async (importOriginal) => {
	const actual = await importOriginal<typeof nodeFs>();
	return {
		...actual,
		createWriteStream: vi.fn((...args: Parameters<typeof actual.createWriteStream>) => {
			if (typeof args[0] === "string") probe.paths.push(args[0]);
			return actual.createWriteStream(...args);
		}),
	};
});

const MiB = 1024 * 1024;
const CAP = FULL_OUTPUT_HEAD_BYTES + FULL_OUTPUT_TAIL_BYTES;
const MARKER_MAX = 1024;
const CHUNK_SIZES = [4097, 5 * MiB + 3, 1, 196613, 9 * MiB + 1];

/** Deterministic lines of 100 bytes whose letters depend on the offset and line number. */
function generate(start: number, length: number): Buffer {
	const buffer = Buffer.allocUnsafe(length);
	for (let i = 0; i < length; i++) {
		const offset = start + i;
		buffer[i] = offset % 100 === 99 ? 0x0a : 0x61 + ((offset * 31 + Math.floor(offset / 100)) % 26);
	}
	return buffer;
}

/** Operations that stream `total` generated bytes in uneven chunks, then exit or throw. */
function streamingOperations(total: number, end: () => { exitCode: number }): BashOperations {
	return {
		exec: async (_command, _cwd, { onData }) => {
			for (let offset = 0, i = 0; offset < total; i++) {
				const length = Math.min(CHUNK_SIZES[i % CHUNK_SIZES.length], total - offset);
				onData(generate(offset, length));
				offset += length;
			}
			return end();
		},
	};
}

function runTool(operations: BashOperations) {
	const tool = wrapToolDefinition(createBashToolDefinition(tmpdir(), { operations }));
	return tool.execute("bash-output-cap", { command: "fake wide rg" });
}

function expectCappedLog(path: string, total: number): void {
	const file = readFileSync(path);
	expect(statSync(path).size).toBeLessThanOrEqual(CAP + MARKER_MAX);
	expect(file.subarray(0, FULL_OUTPUT_HEAD_BYTES).equals(generate(0, FULL_OUTPUT_HEAD_BYTES))).toBe(true);
	expect(
		file
			.subarray(file.length - FULL_OUTPUT_TAIL_BYTES)
			.equals(generate(total - FULL_OUTPUT_TAIL_BYTES, FULL_OUTPUT_TAIL_BYTES)),
	).toBe(true);
}

function expectCapNotice(text: string, path: string, omitted: number): void {
	expect(text).toContain(path);
	expect(text).toMatch(/cap/i);
	expect(text.includes(String(omitted)) || text.includes(formatSize(omitted))).toBe(true);
}

describe("bash full output cap (smarty-dev#11307)", () => {
	it("leaves small tool output and structured output unchanged", async () => {
		const text = "small output ☃\n";
		const result = await runTool({
			exec: async (_command, _cwd, { onData }) => {
				onData(Buffer.from(text));
				return { exitCode: 0 };
			},
		});
		expect(result.content).toEqual([{ type: "text", text }]);
		expect(result.details).toBeUndefined();
		const structured = (result as { structuredContent?: BashToolOutput }).structuredContent;
		expect(structured?.output).toBe(text);
		expect(structured?.truncated).toBe(false);
		expect(structured?.full_output_path).toBeUndefined();
	});

	it.skipIf(process.platform === "win32")("caps a real local shell's 50 MiB output", async () => {
		const total = 50 * MiB;
		const tool = wrapToolDefinition(createBashToolDefinition(tmpdir()));
		const result = await tool.execute("bash-real-output-cap", {
			command: `head -c ${total} /dev/zero`,
		});
		const details = result.details as { fullOutputPath?: string };
		const path = details.fullOutputPath as string;
		const file = readFileSync(path);
		expect(file.length).toBeLessThanOrEqual(CAP + MARKER_MAX);
		expect(file.subarray(0, FULL_OUTPUT_HEAD_BYTES).equals(Buffer.alloc(FULL_OUTPUT_HEAD_BYTES))).toBe(true);
		expect(file.subarray(-FULL_OUTPUT_TAIL_BYTES).equals(Buffer.alloc(FULL_OUTPUT_TAIL_BYTES))).toBe(true);
		const block = result.content[0];
		if (block.type !== "text") throw new Error("Expected text output");
		expectCapNotice(block.text, path, total - CAP);
	});

	// smarty-dev#11307: one wide rg wrote a 2.37 GB log; 50 MiB stands in for it here.
	it("keeps the model tail, caps the log and reports the cap for a 50 MiB stream", async () => {
		const total = 50 * MiB;
		const omitted = total - CAP;
		const pathsBefore = probe.paths.length;
		const diskBefore = getOutputDirectoryBytes();
		const result = await runTool(streamingOperations(total, () => ({ exitCode: 0 })));
		const path = probe.paths[pathsBefore];
		expect(probe.paths).toHaveLength(pathsBefore + 1);
		expect(getOutputDirectoryBytes() - diskBefore).toBeLessThanOrEqual(CAP + MARKER_MAX);

		const details = result.details as { fullOutputPath?: string; truncation?: { truncated: boolean } };
		expect(details.fullOutputPath).toBe(path);
		expect(details.truncation?.truncated).toBe(true);
		expectCappedLog(path, total);

		// The model-facing tail is unchanged by the cap: the last lines within the display limits.
		const block = result.content[0];
		if (block.type !== "text") throw new Error("Expected text output");
		const window = 200_000;
		const expectedTail = truncateTail(generate(total - window, window).toString("latin1")).content;
		expect(block.text.startsWith(`${expectedTail}\n\n`)).toBe(true);
		expectCapNotice(block.text.slice(expectedTail.length), path, omitted);

		const structured = (result as { structuredContent?: BashToolOutput }).structuredContent;
		expect(structured?.truncated).toBe(true);
		expect(structured?.full_output_path).toBe(path);
		expect(structured?.exit_code).toBe(0);
		expect(structured?.output.endsWith(generate(total - 4096, 4096).toString("latin1"))).toBe(true);
	});

	it("caps the log and reports the cap for a nonzero exit", async () => {
		const total = 50 * MiB;
		const pathsBefore = probe.paths.length;
		const result = await runTool(streamingOperations(total, () => ({ exitCode: 3 })));
		const path = probe.paths[pathsBefore];
		const block = result.content[0];
		if (block.type !== "text") throw new Error("Expected text output");
		expect(block.text).toContain("Command exited with code 3");
		expectCapNotice(block.text, path, total - CAP);
		expectCappedLog(path, total);
		const structured = (result as { structuredContent?: BashToolOutput }).structuredContent;
		expect(structured?.truncated).toBe(true);
		expect(structured?.exit_code).toBe(3);
	});

	it("caps the log and reports the cap when the command is aborted", async () => {
		const total = CAP + MiB;
		const pathsBefore = probe.paths.length;
		const run = runTool(
			streamingOperations(total, () => {
				throw new Error("aborted");
			}),
		);
		const error = await run.then(
			() => undefined,
			(caught: unknown) => caught,
		);
		expect(error).toBeInstanceOf(Error);
		const message = (error as Error).message;
		const path = probe.paths[pathsBefore];
		expect(message).toContain("Command aborted");
		expectCapNotice(message, path, MiB);
		expectCappedLog(path, total);
	});

	// Audit finding 1: a backend that emits over-cap output and then fails must still report the cap.
	it("keeps the original error and adds the cap when the backend fails after over-cap output", async () => {
		const total = CAP + MiB;
		const pathsBefore = probe.paths.length;
		const cause = new Error("socket reset");
		const original = Object.assign(new Error("remote disconnect", { cause }), { code: "ECONNRESET" });
		const error = await runTool(
			streamingOperations(total, () => {
				throw original;
			}),
		).then(
			() => undefined,
			(caught: unknown) => caught,
		);
		const path = probe.paths[pathsBefore];
		expect(probe.paths).toHaveLength(pathsBefore + 1);
		expect(error).toBe(original);
		expect(original.cause).toBe(cause);
		expect(original.code).toBe("ECONNRESET");
		expect(original.message.startsWith("remote disconnect\n\n")).toBe(true);
		expectCapNotice(original.message, path, MiB);
		expectCappedLog(path, total);
	});

	it("rethrows an uncapped backend failure unchanged", async () => {
		const original = new Error("remote disconnect");
		const error = await runTool(
			streamingOperations(MiB, () => {
				throw original;
			}),
		).then(
			() => undefined,
			(caught: unknown) => caught,
		);
		expect(error).toBe(original);
		expect(original.message).toBe("remote disconnect");
	});
});
